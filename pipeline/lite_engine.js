// Builds lite/engine.js: the analysis code of the full app (web/index.html), copied function by function so the lite app runs
// exactly the same validated code. Loads web/index.html in headless Chromium, starts from the root functions below and
// follows every global name they use (transitively); functions are copied with Function.prototype.toString, constants
// serialised (typed arrays rebuilt). Data holders filled by loaders (CNN, SEG, MODELS) are declared empty; lite/index.html fills them.
//   node pipeline/lite_engine.js
const { open, ROOT } = require('../tests/helpers'); const fs = require('fs'); const path = require('path');
const ROOTS = ['parseWav', 'normalisePeak', 'decodeToSR', 'analyzeSignal', 'recordingFeatures', 'modelProba', 'cnnMurmur', 'segmentHeartSounds', 'hrvFromTimes'];
const HOLDERS = ['CNN', 'SEG', 'MODELS', 'ICBHI'];
(async () => {
  const { page: pg, url, close } = await open({ port: 8785 });
  await pg.goto('about:blank'); const builtins = new Set(await pg.evaluate(() => Object.getOwnPropertyNames(window)));
  await pg.goto(url('#none')); await pg.waitForFunction(() => typeof analyzeSignal === 'function');
  const res = await pg.evaluate(([roots, holders, builtins]) => {
    const B = new Set(builtins), seen = new Map(), queue = [...roots], skipped = [];
    const KW = new Set('if else for while do return function const let var new typeof instanceof in of break continue switch case default try catch finally throw this null true false undefined async await class extends super yield delete void with'.split(' '));
    const get = n => { try { return { ok: true, v: eval(n) } } catch (e) { return { ok: false } } };
    while (queue.length) {
      const n = queue.shift(); if (seen.has(n) || holders.includes(n) || KW.has(n) || B.has(n)) continue;
      const g = get(n); if (!g.ok) continue; const v = g.v; let src = null, kind = null;
      if (typeof v === 'function') { src = v.toString(); if (/\[native code\]/.test(src)) continue; kind = 'fn'; if (!/^(async\s+)?function\b/.test(src)) { src = `const ${n}=${src};`; kind = 'arrow' } }
      else if (v === null || ['number', 'string', 'boolean'].includes(typeof v)) { src = `let ${n}=${JSON.stringify(v)};`; kind = 'val' }
      else if (ArrayBuffer.isView(v)) { src = `let ${n}=new ${v.constructor.name}([${Array.from(v).join(',')}]);`; kind = 'typed' }
      else if (Array.isArray(v) || Object.getPrototypeOf(v) === Object.prototype) {
        try { src = `let ${n}=${JSON.stringify(v, (k, x) => ArrayBuffer.isView(x) ? Array.from(x) : x)};`; kind = 'obj' } catch (e) { skipped.push(n); continue }
        if (/function/.test(String(Object.values(v).find(x => typeof x === 'function') || ''))) { skipped.push(n + ' (has functions)'); continue }
      } else { skipped.push(n + ' (' + Object.prototype.toString.call(v) + ')'); continue }
      seen.set(n, { kind, src });
      if (kind === 'fn' || kind === 'arrow') for (const id of new Set(src.match(/[A-Za-z_$][\w$]*/g) || [])) if (!seen.has(id) && !B.has(id) && !KW.has(id)) queue.push(id);
    }
    return { items: [...seen.entries()].map(([n, x]) => ({ n, ...x })), skipped };
  }, [ROOTS, HOLDERS, [...builtins]]);
  await close();
  const order = { val: 0, typed: 0, obj: 1, arrow: 2, fn: 3 };
  const items = res.items.sort((a, b) => order[a.kind] - order[b.kind]);
  const out = `// AUTO-GENERATED by pipeline/lite_engine.js from web/index.html — do not edit; rerun after analysis code changes.\n` +
    `let ${HOLDERS.join('=null,')}=null;\n` + items.map(i => i.src.replace(/^function /, 'function ').trim()).join('\n') + '\n';
  fs.mkdirSync(path.join(ROOT, 'lite'), { recursive: true }); fs.writeFileSync(path.join(ROOT, 'lite', 'engine.js'), out);
  console.log(items.length, 'declarations,', (out.length / 1024).toFixed(0), 'KB; names:', items.map(i => i.n).join(' '));
  if (res.skipped.length) console.log('skipped:', res.skipped.join(', '));
})();
